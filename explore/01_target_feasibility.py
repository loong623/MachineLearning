import sys, numpy as np, pandas as pd
df = pd.read_csv(sys.argv[1], parse_dates=["Date"])
print(df.shape, df.Date.min(), df.Date.max(), df.Location.nunique())
print((df.isna().mean()*100).round(1).sort_values(ascending=False).head(10).to_dict())
print("RainTomorrow yes%", round((df.RainTomorrow=="Yes").mean()*100,1))
df = df.sort_values(["Location","Date"])
g = df.groupby("Location")
nxt = lambda c: g[c].shift(-1)
consec = (g["Date"].shift(-1) - df["Date"]).dt.days.eq(1)
print("consecutive next-day rows %", round(consec.mean()*100,1))
def rate(name, lab, avail):
    m = consec & avail
    print(f"{name:28s} pos%={lab[m].mean()*100:5.1f}  usable_rows={m.sum()}")
rate("Frost: MinT_next<=2", nxt("MinTemp")<=2, nxt("MinTemp").notna())
rate("Hot: MaxT_next>=35", nxt("MaxTemp")>=35, nxt("MaxTemp").notna())
rate("CoolChange: dMaxT<=-8", (nxt("MaxTemp")-df.MaxTemp)<=-8, nxt("MaxTemp").notna()&df.MaxTemp.notna())
rate("Gale: Gust_next>=63", nxt("WindGustSpeed")>=63, nxt("WindGustSpeed").notna())
rate("Solar: Sun_next>=10h", nxt("Sunshine")>=10, nxt("Sunshine").notna())
rate("HeavyRain: Rain_next>=25", nxt("Rainfall")>=25, nxt("Rainfall").notna())
# simplified FFDI, drought factor fixed at 8 (assumption)
T,H,V = nxt("MaxTemp"), nxt("Humidity3pm"), nxt("WindSpeed3pm")
ffdi = 2*np.exp(-0.45+0.987*np.log(8)-0.0345*H+0.0338*T+0.0234*V)
rate("Fire: FFDI_next>=25 (DF=8)", ffdi>=25, ffdi.notna())
rate("Fire: FFDI_next>=12 (DF=8)", ffdi>=12, ffdi.notna())
# month/season balance
s = df.Date.dt.month.map({12:"Sum",1:"Sum",2:"Sum",3:"Aut",4:"Aut",5:"Aut",6:"Win",7:"Win",8:"Win",9:"Spr",10:"Spr",11:"Spr"})
print("season", (s.value_counts(normalize=True)*100).round(1).to_dict())
print("rows/location min/max", g.size().min(), g.size().max())
print("locations with Sunshine mostly present", (g["Sunshine"].apply(lambda x:x.notna().mean())>0.5).sum())
print(sorted(df.Location.unique()))
